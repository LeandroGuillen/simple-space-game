import "math/rand"

func init() {
	rand.Shuffle(len(STAR_NAMES), func(i int, j int) {
		STAR_NAMES[i], STAR_NAMES[j] = STAR_NAMES[j], STAR_NAMES[i]
	})
}

func MaxStars() int {
	return len(STAR_NAMES)
}

func GetRandomStarName() string {
	//if len(STAR_NAMES) == 0 {
	//	return "NO_STARS_LEFT"
	//}
	newName := STAR_NAMES[rand.Intn(len(STAR_NAMES))]
	//STAR_NAMES = removeIndex(STAR_NAMES, 0)
	return newName
}

func removeIndex(s []string, index int) []string {
	return append(s[:index], s[index+1:]...)
}

